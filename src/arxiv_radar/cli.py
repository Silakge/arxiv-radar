"""Command-line interface for arxiv-radar."""

from __future__ import annotations

import argparse
import os
import sys
from datetime import date

from arxiv_radar import __version__
from arxiv_radar.arxiv import ArxivError, fetch_recent, filter_window
from arxiv_radar.config import (
    CONFIG_TEMPLATE,
    ConfigError,
    load_config,
    zero_config,
)
from arxiv_radar.dedup import SeenStore
from arxiv_radar.llm import enrich
from arxiv_radar.models import Digest
from arxiv_radar.render import write_digest
from arxiv_radar.scoring import score_papers, sort_final

DEFAULT_CONFIG_NAME = "radar.yaml"

INIT_TEMPLATE = """\
# 📡 arxiv-radar configuration (generated by `arxiv-radar init`)

radar:
  name: {name}
  days: {days}
  max_papers: {max_papers}

arxiv:
  categories: {categories}
  keywords:
{keywords_block}
  exclude: []

interests:                    # omit to score keywords with weight 1
{interests_block}

llm:
  enabled: {llm_enabled}
  base_url: {base_url}
  model: {model}
  api_key_env: {api_key_env}
  max_papers: {llm_max_papers}

output:
  dir: digest
  formats: [md, html, rss]
"""


def _utf8_console() -> None:
    """Windows consoles may default to a legacy code page; force UTF-8 output."""
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[union-attr]
        except Exception:
            pass


def _resolve_config(args: argparse.Namespace):
    """Load the config file, falling back to built-in demo interests."""
    path = args.config
    if path and os.path.exists(path):
        return load_config(path), path
    if not path:
        path = DEFAULT_CONFIG_NAME
        if os.path.exists(path):
            return load_config(path), path
        print(
            "ℹ️  No radar.yaml found - using built-in demo interests. "
            "Run `arxiv-radar init` to customize.\n"
        )
        return zero_config(), None
    return load_config(path), path  # load_config raises a friendly error


def _apply_overrides(cfg, args: argparse.Namespace) -> None:
    if args.days is not None:
        cfg.days = args.days
    if args.limit is not None:
        cfg.max_papers = args.limit
    if args.out is not None:
        cfg.output_dir = args.out
    cfg.validated()


# --------------------------------------------------------------------------
# init
# --------------------------------------------------------------------------

def cmd_init(args: argparse.Namespace) -> int:
    if os.path.exists(args.config) and not args.force:
        print(
            f"✋ {args.config} already exists (use --force to overwrite).\n"
            f"   Edit it directly, or delete it first."
        )
        return 1
    if not sys.stdin.isatty():
        with open(args.config, "w", encoding="utf-8") as fh:
            fh.write(CONFIG_TEMPLATE)
        print(f"✅ Wrote {args.config} with commented defaults. Open it and edit your interests.")
        return 0

    try:
        return _init_interactive(args)
    except EOFError:
        # Piped/CI environments can report a tty yet deliver EOF on input.
        with open(args.config, "w", encoding="utf-8") as fh:
            fh.write(CONFIG_TEMPLATE)
        print(f"\n✅ No interactive terminal detected - wrote {args.config} with commented defaults instead.")
        return 0


def _init_interactive(args: argparse.Namespace) -> int:
    print("📡 Let's set up your radar (press Enter to accept [defaults]).\n")
    name = input("Radar name [My Research Radar]: ").strip() or "My Research Radar"
    keywords_raw = input("Keywords, comma-separated [large language model, LLM agents]: ").strip()
    keywords = [k.strip() for k in keywords_raw.split(",") if k.strip()] or [
        "large language model",
        "LLM agents",
    ]
    categories_raw = input("arXiv categories, comma-separated [cs.CL, cs.LG]: ").strip()
    categories = [c.strip() for c in categories_raw.split(",") if c.strip()]
    days_raw = input("Look-back window in days [3]: ").strip()
    days = int(days_raw) if days_raw.isdigit() and int(days_raw) > 0 else 3
    max_raw = input("Max papers per digest [20]: ").strip()
    max_papers = int(max_raw) if max_raw.isdigit() and int(max_raw) > 0 else 20

    llm_enabled = input("Enable LLM summaries? y/[N]: ").strip().lower() in {"y", "yes"}
    base_url, model, api_key_env = "https://api.openai.com/v1", "gpt-4o-mini", "PAPER_RADAR_API_KEY"
    if llm_enabled:
        base_url = input(f"Base URL [{base_url}]: ").strip() or base_url
        model = input(f"Model [{model}]: ").strip() or model
        api_key_env = input(f"Env var holding the API key [{api_key_env}]: ").strip() or api_key_env

    keywords_block = "\n".join(f"      - {k}" for k in keywords)
    interests_block = "\n".join(f'  - "{k}": 2' for k in keywords) or '  - "placeholder": 1'
    text = INIT_TEMPLATE.format(
        name=name,
        days=days,
        max_papers=max_papers,
        categories=("[" + ", ".join(categories) + "]") if categories else "[]",
        keywords_block=keywords_block,
        interests_block=interests_block,
        llm_enabled="true" if llm_enabled else "false",
        base_url=base_url,
        model=model,
        api_key_env=api_key_env,
        llm_max_papers=max_papers,
    )
    with open(args.config, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"\n✅ Wrote {args.config}")
    print("   Next: edit your interests, then run `arxiv-radar run`.")
    if llm_enabled:
        print(f"   Remember to export {api_key_env}=<your key> before running.")
    return 0


# --------------------------------------------------------------------------
# check
# --------------------------------------------------------------------------

def cmd_check(args: argparse.Namespace) -> int:
    cfg, path = _resolve_config(args)
    source = path or "(built-in demo config)"
    print(f"📋 Config: {source}")
    print(f"   name        : {cfg.name}")
    print(f"   window      : last {cfg.days} days")
    print(f"   max_papers  : {cfg.max_papers}")
    print(f"   categories  : {cfg.categories or '(any)'}")
    print(f"   keywords    : {cfg.keywords or '(none)'}")
    print(f"   exclude     : {cfg.exclude or '(none)'}")
    print(f"   interests   : " + ", ".join(f"{k} ×{w:g}" for k, w in cfg.interests.items()))
    print(f"   output      : {cfg.output_dir}/  formats={','.join(cfg.formats)}")
    llm_state = "enabled" if cfg.llm.enabled else "disabled (pure keyword mode)"
    if cfg.llm.enabled:
        key_set = "set ✔" if os.environ.get(cfg.llm.api_key_env) else f"NOT set ✘ (export {cfg.llm.api_key_env})"
        llm_state += f" · {cfg.llm.model} @ {cfg.llm.base_url} · key {cfg.llm.api_key_env}: {key_set}"
    print(f"   llm         : {llm_state}")
    from arxiv_radar.arxiv import build_query

    print(f"\n🔎 arXiv query:\n   {build_query(cfg.categories, cfg.keywords) or '(empty!)'}")
    return 0


# --------------------------------------------------------------------------
# run
# --------------------------------------------------------------------------

def cmd_run(args: argparse.Namespace) -> int:
    cfg, path = _resolve_config(args)
    _apply_overrides(cfg, args)

    print(f"📡 {cfg.name} · {date.today().isoformat()} · window: last {cfg.days} days")
    query, papers = fetch_recent(cfg)
    in_window = filter_window(papers, cfg.days)
    print(f"   fetched {len(papers)} recent submissions · {len(in_window)} within window")

    scored = score_papers(in_window, cfg.interests, cfg.exclude)
    print(f"   {len(scored)} match your interests (keyword scoring)")

    seen = SeenStore(os.path.join(cfg.output_dir, "seen.json"))
    fresh = [sp for sp in scored if not seen.is_seen(sp.paper.arxiv_id)]
    skipped = len(scored) - len(fresh)
    if skipped:
        print(f"   {skipped} already in previous digests (seen.json)")
    top = fresh[: cfg.max_papers]

    llm_used = False
    if cfg.llm.enabled and not args.no_llm and top:
        candidates = top[: cfg.llm.max_papers]
        verdicts = enrich(candidates, cfg.llm, cfg.interests)
        for sp in top:
            verdict = verdicts.get(sp.paper.arxiv_id)
            if verdict:
                sp.llm_relevance = verdict["relevance"]
                sp.llm_tldr = verdict["tldr"]
                sp.llm_reason = verdict["reason"]
        llm_used = bool(verdicts)
        if llm_used:
            print(f"   🤖 LLM enriched {len(verdicts)} papers")
            top = sort_final(top)

    if not top:
        seen.prune()
        seen.save()
        print("\n✅ No new papers matched today - nothing to do. Try widening `days` or keywords.")
        return 0

    digest = Digest(
        radar_name=cfg.name,
        digest_date=date.today(),
        window_days=cfg.days,
        fetched=len(papers),
        matched_count=len(scored),
        query=query,
        llm_used=llm_used,
        papers=top,
    )
    files = write_digest(digest, cfg.output_dir, cfg.formats)
    seen.mark([sp.paper.arxiv_id for sp in top])
    seen.prune()
    seen.save()

    print(f"\n✅ Digest ready · showing {len(top)} papers (top score {top[0].score}/100):")
    for file_path in files:
        print(f"   {file_path}")
    html = next((f for f in files if f.endswith(".html")), None)
    if html:
        print(f"💡 Open {html} in a browser for the full experience.")
    return 0


# --------------------------------------------------------------------------
# argument parsing
# --------------------------------------------------------------------------

def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="arxiv-radar",
        description=(
            "Track your research field on autopilot: fetch fresh arXiv papers, "
            "rank them against your interests, and render a daily digest "
            "(Markdown / HTML / RSS)."
        ),
    )
    parser.add_argument("--version", action="version", version=f"arxiv-radar {__version__}")
    sub = parser.add_subparsers(dest="command", required=True)

    p_init = sub.add_parser("init", help="create a radar.yaml config interactively")
    p_init.add_argument("--config", default=DEFAULT_CONFIG_NAME, help="config path (default: radar.yaml)")
    p_init.add_argument("--force", action="store_true", help="overwrite an existing config")
    p_init.set_defaults(func=cmd_init)

    p_run = sub.add_parser("run", help="fetch, score and render today's digest")
    p_run.add_argument("--config", default=None, help="config path (default: ./radar.yaml)")
    p_run.add_argument("--days", type=int, default=None, help="override look-back window")
    p_run.add_argument("--limit", type=int, default=None, help="override max papers per digest")
    p_run.add_argument("--out", default=None, help="override output directory")
    p_run.add_argument("--no-llm", action="store_true", help="skip the LLM pass even if enabled")
    p_run.set_defaults(func=cmd_run)

    p_check = sub.add_parser("check", help="validate the config and show the arXiv query")
    p_check.add_argument("--config", default=None, help="config path (default: ./radar.yaml)")
    p_check.set_defaults(func=cmd_check)
    return parser


def main(argv: list[str] | None = None) -> int:
    _utf8_console()
    args = build_parser().parse_args(argv)
    try:
        return int(args.func(args))
    except ConfigError as exc:
        print(f"✘ Configuration problem:\n{exc}", file=sys.stderr)
        return 2
    except ArxivError as exc:
        print(f"✘ arXiv problem: {exc}", file=sys.stderr)
        return 3
    except KeyboardInterrupt:
        print("\nInterrupted.", file=sys.stderr)
        return 130


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
